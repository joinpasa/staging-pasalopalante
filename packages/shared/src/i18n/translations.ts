// Deep-merge any locale over English so a missing key never renders blank.
function merge<T>(base: T, override: unknown): T {
  if (override === undefined || override === null) return base;
  if (Array.isArray(base)) return (Array.isArray(override) ? override : base) as T;
  if (typeof base === "object" && base !== null && typeof override === "object") {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(base as Record<string, unknown>)) {
      out[key] = merge(
        (base as Record<string, unknown>)[key],
        (override as Record<string, unknown>)[key],
      );
    }
    return out as T;
  }
  return (typeof override === typeof base ? override : base) as T;
}

// Every non-English locale is its own JSON file, loaded only when actually
// needed instead of shipping all ~600KB of every language in the main
// bundle regardless of which one a visitor uses. English is the one locale
// that's always needed (it's the merge base for every other language too),
// so it stays a plain static object above rather than a file of its own.
const loaders: Record<Exclude<Language, "en">, () => Promise<{ default: unknown }>> = {
  es: () => import("./locales/es.json"),
  fr: () => import("./locales/fr.json"),
  de: () => import("./locales/de.json"),
  zh: () => import("./locales/zh.json"),
  hi: () => import("./locales/hi.json"),
  ar: () => import("./locales/ar.json"),
  bn: () => import("./locales/bn.json"),
  pt: () => import("./locales/pt.json"),
  ru: () => import("./locales/ru.json"),
  sl: () => import("./locales/sl.json"),
};

const enTranslations = translations.en as unknown as Translations;
const cache = new Map<Language, Translations>([["en", enTranslations]]);
const pending = new Map<Language, Promise<Translations>>();

/**
 * Loads (and caches) a language's translations, fetching its chunk on
 * first use. Always resolves — a locale whose file fails to load (a
 * network blip, a bad deploy) still resolves to English rather than
 * rejecting, matching this module's existing "never render blank" rule.
 */
export function loadTranslations(lang: Language): Promise<Translations> {
  const cached = cache.get(lang);
  if (cached) return Promise.resolve(cached);

  const existing = pending.get(lang);
  if (existing) return existing;

  const promise = loaders[lang]()
    .then((mod) => merge(enTranslations, mod.default))
    .catch(() => enTranslations)
    .then((value) => {
      cache.set(lang, value);
      pending.delete(lang);
      return value;
    });
  pending.set(lang, promise);
  return promise;
}

/**
 * Synchronous read for a language already loaded via loadTranslations().
 * Falls back to English if it isn't loaded yet (or failed to load) rather
 * than returning nothing — callers that need a guaranteed-loaded locale
 * should await loadTranslations() first (LanguageProvider does, for both
 * the initial language and every later switch).
 */
export function getTranslations(lang: Language): Translations {
  return cache.get(lang) ?? enTranslations;
}

