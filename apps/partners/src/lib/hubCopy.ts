const COPY: Record<Lang, HubCopy> = { en, es };

/** Kind-aware words: "our pledge" for an organisation, "my pledge" for an ambassador. */
export function kindWords(kind: Kind, lang: Lang) {
  const solo = kind === "ambassador";
  if (lang === "es")
    return {
      ourKindness: solo ? "Mi bondad" : "Nuestra bondad",
      teamWord: kind === "company" ? "tus compañeros" : "tu equipo",
      welcomeLine: solo ? "Tu espacio en el movimiento." : kind === "company" ? "El espacio de tu empresa en el movimiento." : "El espacio de tu organización en el movimiento.",
    };
  return {
    ourKindness: solo ? "My kindness" : "Our kindness",
    teamWord: kind === "company" ? "your colleagues" : "your team",
    welcomeLine: solo ? "Your space in the movement." : kind === "company" ? "Your company's space in the movement." : "Your organisation's space in the movement.",
  };
}

export function useHubCopy() {
  const { lang, locale, toggle } = useCopy();
  return { h: COPY[lang] ?? COPY.en, lang, locale, toggle };
}

